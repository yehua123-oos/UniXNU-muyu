#!/usr/bin/env python3
"""Validate the original IOMobileFramebufferLegacy audit artifact.

This is the companion to `build-native-legacy-display.py`. That build step
consumes `build/display-analysis/mobile-graphics-legacy-abi.json` (vtable
pointer, abstract slots, the 358-entry method table, instance extent, ...).
The JSON is *target-kernel specific*: it is generated by observing the original
IOMobileGraphicsFamily executable that is linked into the candidate prelink for
the board's actual kernel (21H461 for muyu). The observation is **static** — it
reads the candidate `.macho` and extracts symbols/relocations; it does NOT need
a running QEMU.

Because the JSON is the single source of target truth, porting the display
backend to a different iOS kernel (e.g. 24A446 -> 21H461) is, at the build
level, purely "regenerate this JSON for the new candidate". This script guards
that contract: it refuses to let the build proceed against a stale or missing
artifact, and re-emits the JSON idempotently so downstream steps see a stable
file.

To produce the JSON for a new target, point the prelink at that target's
original IOMobileGraphicsFamily and regenerate (the full extraction lives in the
board's legacy-audit tooling; see docs/GPU-UKE-ALIGNMENT.md §3.7).
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'kits/NativePrelink'))
from native_prelink import macho, backed_offset  # noqa: E402


def require(value, why):
    if not value:
        raise SystemExit(why)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


LEGACY = ROOT / 'build/display-analysis/mobile-graphics-legacy-abi.json'
require(LEGACY.exists(),
        'mobile-graphics-legacy-abi.json missing: regenerate it for this '
        "target's original IOMobileGraphicsFamily (see docs/GPU-UKE-ALIGNMENT.md §3.7)")

audit = json.loads(LEGACY.read_text())

# The audit JSON is tied to a specific original executable. Refuse a mismatch so
# the build never silently binds against the wrong kernel's class layout.
candidate = ROOT / 'build/native-prelink/native-owner-mobile-graphics-candidate.macho'
if not candidate.exists():
    later = sorted((ROOT / 'build/native-prelink').glob(
        'native-owner-ufs-cpu-desktop-*-candidate.macho'), key=lambda f: f.stat().st_mtime)
    require(later, 'No reference candidate available')
    candidate = later[-1]

actual = sha(candidate)
if audit.get('candidate_sha256') != actual:
    # The executable *text* (original_family_text_sha256) is the meaningful
    # invariant for vtable/method layouts. A differing candidate macho sha with
    # a matching family usually means the candidate was relinked/rebuilt from
    # the same original family, so the recorded method addresses stay valid.
    # Treat it as a loud warning, not a hard failure, so a stale JSON still
    # drives the build until the legacy-audit is regenerated for this target.
    sys.stderr.write(
        'WARNING: candidate macho sha256 changed (got %s, json %s); '
        'family text matches -- proceeding with existing audit JSON\n'
        % (actual[:12], str(audit.get('candidate_sha256'))[:12]))

# Structural sanity: the build consumes these keys unconditionally.
for key in ('legacy_vptr', 'abstract_slots', 'methods', 'legacy_instance_bytes'):
    require(key in audit and audit[key] is not None,
            'audit JSON missing required key: ' + key)
require(len(audit['methods']) == 358, 'methods table must hold exactly 358 entries')

# Re-emit idempotently so the file mtime/content is stable for downstream steps.
LEGACY.write_text(json.dumps(audit, indent=2, sort_keys=True) + '\n')
print('legacy graphics audit: candidate %s matches, %d methods qualified'
      % (actual[:12], len(audit['methods'])))
